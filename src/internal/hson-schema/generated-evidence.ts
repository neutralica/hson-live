import { createHash } from "node:crypto";

import { encode_canonical_schema_graph_hson } from "../canonical-schema/encode-hson.js";
import { compile_hson_schema, type CompiledHsonSchema } from "./compiler.js";
import { generate_hson_schema_types } from "./generate-types.js";

export type GeneratedHsonSchemaEvidence = Readonly<{ compiled: CompiledHsonSchema; declaration: string; metadata: string; generatedBytes: number; proofNodeCount: number }>;

export function generate_hson_schema_evidence(schemaName: string, source: string, declarationIdentity: string): GeneratedHsonSchemaEvidence {
  const compiled = compile_hson_schema(source);
  if (!compiled.ok) throw new Error(compiled.issues.map(issue => issue.message).join(" "));
  const generated = generate_hson_schema_types(schemaName, compiled.value.semantic, compiled.value.definitions);
  const generatedHsonNodeImport = generated.declarations.includes("HsonNode") ? 'import type { HsonNode } from "hson-live/hson";\n' : "";
  const readType = generated.declarations.includes("$SchemaDataRead") || generated.declarations.includes("$SchemaObjectRead")
    ? 'type $SchemaDataRead = import("hson-live/hson").JsonFromSchema<typeof import("hson-live/hson").ANY_DATA>;\n' : "";
  const objectType = generated.declarations.includes("$SchemaObjectRead")
    ? 'type $SchemaObjectRead = globalThis.Extract<$SchemaDataRead, { readonly [name: string]: unknown }>;\n' : "";
  const inputType = generated.declarations.includes("$SchemaDataInput")
    ? 'type $SchemaDataInput = globalThis.Exclude<import("hson-live/hson").HsonDataInput, import("hson-live/hson").HsonDataValue>;\n' : "";
  const declaration = `/* Generated by Hson Schema. Do not edit. */\n${generatedHsonNodeImport}${readType}${objectType}${inputType}${generated.declarations}\n`;
  const graphHson = encode_canonical_schema_graph_hson(compiled.value.graph);
  const metadata = `${JSON.stringify({ declarationIdentity, sourceDigest: digest(source), semanticGraphDigest: digest(graphHson), generatedDeclarationDigest: digest(declaration), graphHson }, null, 2)}\n`;
  return Object.freeze({ compiled: compiled.value, declaration, metadata, generatedBytes: Buffer.byteLength(declaration), proofNodeCount: generated.proofNodeCount });
}

function digest(value: string): string { return createHash("sha256").update(value).digest("hex"); }
